#!/usr/bin/env python3
"""
Stablecoin Visualization Script

This script reads the CSV files generated by stats.py and creates five plots:
1. Daily transacted volume for all stablecoins
2. Daily transaction count for all stablecoins
3. Daily different addresses involved in stablecoin transactions
4. Daily DeFi protocol transactions for all stablecoins
5. Daily Rollup protocol transactions for all stablecoins

All plots show days on the x-axis with different colors for each stablecoin
and include legends.
"""

import glob

import matplotlib
import matplotlib.dates as mdates
import matplotlib.pyplot as plt
import pandas as pd

matplotlib.use('Agg')  # Use non-interactive backend


def load_stablecoin_data():
    """Load all available stablecoin daily stats CSV files"""
    stablecoin_data = {}

    # Find all daily stats CSV files
    csv_files = glob.glob("*_daily_stats.csv")

    print("Found {} stablecoin data files:".format(
        len(csv_files)))

    for csv_file in csv_files:
        # Extract stablecoin name from filename
        stablecoin_name = csv_file.replace("_daily_stats.csv", "")

        try:
            # Read the CSV file
            df = pd.read_csv(csv_file)

            # Convert date column to datetime
            df['date'] = pd.to_datetime(df['date'])

            # Extract volume and transaction count columns
            volume_col = "total_volume_{}".format(stablecoin_name)
            tx_count_col = "transaction_count"

            if volume_col in df.columns and tx_count_col in df.columns:
                # Store the data
                # Check if different_addresses and defi columns exist
                different_addr = None
                if 'different_addresses' in df.columns:
                    different_addr = df['different_addresses']

                defi_txs = None
                rollup_txs = None
                if 'defi_transaction_count' in df.columns:
                    defi_txs = df['defi_transaction_count']
                if 'rollup_transaction_count' in df.columns:
                    rollup_txs = df['rollup_transaction_count']

                stablecoin_data[stablecoin_name] = {
                    'dates': df['date'],
                    'volume': df[volume_col],
                    'transaction_count': df[tx_count_col],
                    'different_addresses': different_addr,
                    'defi_transaction_count': defi_txs,
                    'rollup_transaction_count': rollup_txs
                }
                print("  ✓ {}: {} days of data".format(
                    stablecoin_name.upper(), len(df)))
            else:
                print("  ✗ {}: Missing required columns".format(
                    stablecoin_name.upper()))

        except Exception as e:
            print("  ✗ {}: Error reading file - {}".format(
                stablecoin_name.upper(), e))

    return stablecoin_data


def create_volume_plot(stablecoin_data):
    """Create a plot showing daily transacted volume for all stablecoins"""
    plt.figure(figsize=(12, 8))

    # Define colors for different stablecoins
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728', '#9467bd', '#8c564b']

    for i, (stablecoin_name, data) in enumerate(stablecoin_data.items()):
        color = colors[i % len(colors)]
        plt.plot(data['dates'], data['volume'],
                 label=stablecoin_name.upper(),
                 color=color,
                 linewidth=2,
                 marker='o',
                 markersize=4)

    plt.title('Daily Stablecoin Transaction Volume',
              fontsize=16, fontweight='bold')
    plt.xlabel('Date', fontsize=12)
    plt.ylabel('Volume (Tokens)', fontsize=12)
    plt.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
    plt.grid(True, alpha=0.3)

    # Format x-axis to show dates nicely
    plt.gca().xaxis.set_major_formatter(mdates.DateFormatter('%Y-%m-%d'))
    plt.gca().xaxis.set_major_locator(mdates.DayLocator(interval=3))
    plt.xticks(rotation=45)

    # Format y-axis to show large numbers with commas and set log scale
    ax = plt.gca()
    ax.set_yscale('log')
    ax.yaxis.set_major_formatter(
        plt.FuncFormatter(lambda x, p: '{:,.0f}'.format(x)))

    plt.tight_layout()
    plt.savefig('stablecoin_volume_plot.png',
                dpi=300, bbox_inches='tight')
    print("✓ Volume plot saved as 'stablecoin_volume_plot.png'")

    return plt


