def print_summary_stats(stablecoin_data):
    """Print summary statistics for all stablecoins"""
    print("\n" + "="*80)
    print("SUMMARY STATISTICS")
    print("="*80)

    for stablecoin_name, data in stablecoin_data.items():
        total_volume = data['volume'].sum()
        total_transactions = data['transaction_count'].sum()
        avg_daily_volume = data['volume'].mean()
        avg_daily_transactions = data['transaction_count'].mean()

        # Calculate different addresses and DeFi stats if available
        if data['different_addresses'] is not None:
            avg_daily_different_addresses = data['different_addresses'].mean()
            max_daily_different_addresses = data['different_addresses'].max()

        if data['defi_transaction_count'] is not None:
            avg_daily_defi_transactions = data['defi_transaction_count'].mean()
            max_daily_defi_transactions = data['defi_transaction_count'].max()

        if data['rollup_transaction_count'] is not None:
            avg_daily_rollup_transactions = (
                data['rollup_transaction_count'].mean())
            max_daily_rollup_transactions = (
                data['rollup_transaction_count'].max())

        print("\n{}:".format(stablecoin_name.upper()))
        print("  Total Volume: {:.2f} tokens".format(
            total_volume))
        print("  Total Transactions: {:,}".format(total_transactions))
        print("  Average Daily Volume: {:.2f} tokens".format(
            avg_daily_volume))
        print("  Average Daily Transactions: {:.0f}".format(
            avg_daily_transactions))
        if data['different_addresses'] is not None:
            print("  Average Daily Different Addresses: {:.0f}".format(
                avg_daily_different_addresses))
            print("  Max Daily Different Addresses: {:,}".format(
                max_daily_different_addresses))
        if data['defi_transaction_count'] is not None:
            print("  Average Daily DeFi Transactions: {:.0f}".format(
                avg_daily_defi_transactions))
            print("  Max Daily DeFi Transactions: {:,}".format(
                max_daily_defi_transactions))
        if data['rollup_transaction_count'] is not None:
            print("  Average Daily Rollup Transactions: {:.0f}".format(
                avg_daily_rollup_transactions))
            print("  Max Daily Rollup Transactions: {:,}".format(
                max_daily_rollup_transactions))


def main():
    """Main function to create both plots"""
    print("Stablecoin Visualization Script")
    print("="*40)

    # Load data from CSV files
    stablecoin_data = load_stablecoin_data()

    if not stablecoin_data:
        print("No stablecoin data found! Make sure you have run "
              "stats.py first.")
        return

    print("\nLoaded data for {} stablecoins".format(
        len(stablecoin_data)))

